// node test/acct-pick.test.js   (the Auto account picker: pure functions cut out of server.js, no server started)
"use strict";
const assert = require("assert"), fs = require("fs"), path = require("path");
const src = fs.readFileSync(path.join(__dirname, "..", "server.js"), "utf8");
const m = src.match(/\/\/ <acct-pick>[^\n]*\n([\s\S]*?)\/\/ <\/acct-pick>/);
assert(m, "acct-pick block not found in server.js");
const { pickAccount, autoShouldMove } = new Function(m[1] + "\nreturn { pickAccount, autoShouldMove };")();
let n = 0; const ok = (name, got, want) => { assert.deepStrictEqual(got, want, name); n++; console.log("ok   " + name); };
const A = (n, five, week = 10, extra = {}) => ({ n, key: true, held: false, five, week, ...extra });

ok("0% wins over a busier account", pickAccount([A(1, 40), A(2, 0)]), 2);
ok("0% wins even against the sticky current pick", pickAccount([A(1, 3), A(2, 0)], 1), 2);
ok("lowest 5-hour wins", pickAccount([A(1, 12), A(2, 55)]), 1);
ok("tie on 5-hour -> lowest weekly", pickAccount([A(1, 20, 60), A(2, 20, 30)]), 2);
ok("both 0% -> lowest weekly", pickAccount([A(1, 0, 50), A(2, 0, 5)]), 2);
ok("full tie -> account 1", pickAccount([A(1, 0, 5), A(2, 0, 5)]), 1);
ok("at the governor's 98% line -> skipped", pickAccount([A(1, 98), A(2, 99.5)]), null);
ok("over the line -> the other one, even if much higher", pickAccount([A(1, 99), A(2, 80)]), 2);
ok("weekly spent -> skipped", pickAccount([A(1, 5, 98), A(2, 60, 20)]), 2);
ok("missing key -> skipped", pickAccount([A(1, 50), A(2, 0, 0, { key: false })]), 1);
ok("held by the governor -> skipped", pickAccount([A(1, 50), A(2, 0, 0, { held: true })]), 1);
ok("no reading -> skipped", pickAccount([A(1, null), A(2, 30)]), 2);
ok("no readings at all -> null (caller falls back to the switch)", pickAccount([A(1, null), A(2, null)]), null);
ok("sticky: current pick kept when the other is under 5 points lower", pickAccount([A(1, 22), A(2, 19)], 1), 1);
ok("sticky ends at 5 points", pickAccount([A(1, 24), A(2, 19)], 1), 2);
ok("no-cap account goes first even when the capped one is at 0%", pickAccount([A(1, 0, 69, { nocap: true }), A(2, 0, 20)]), 1);
ok("no-cap account past 90% of its week -> the capped one", pickAccount([A(1, 0, 91, { nocap: true }), A(2, 40, 50)]), 2);
ok("no-cap past 90% still used when the capped one is out", pickAccount([A(1, 0, 91, { nocap: true }), A(2, 99, 50)]), 1);
ok("sticky does not hold a capped chat off the no-cap account", pickAccount([A(1, 0, 60, { nocap: true }), A(2, 3, 50)], 2), 1);
ok("idle chat on a no-cap account past 90% week moves", autoShouldMove(A(1, 0, 92, { nocap: true }), A(2, 30, 50)), "week");
ok("idle capped chat is not pulled back to a no-cap account past 90% week", autoShouldMove(A(2, 40, 50), A(1, 0, 92, { nocap: true })), false);
ok("idle chat on a no-cap account under 90% week stays", autoShouldMove(A(1, 0, 70, { nocap: true }), A(2, 0, 50)), false);
ok("sticky never keeps a spent pick", pickAccount([A(1, 98), A(2, 95)], 1), 2);

ok("90%: account at 90 -> move to the lower one", autoShouldMove(A(1, 90), A(2, 80)), "90");
ok("90%: account at 92, other 85 (7 pts) -> move (90 beats the 15-pt gap)", autoShouldMove(A(1, 92), A(2, 85)), "90");
ok("90%: at 89 -> not yet (gap rule only)", autoShouldMove(A(1, 89), A(2, 80)), false);
ok("90%: both over 90, other 3 lower -> stay (no flapping)", autoShouldMove(A(1, 94), A(2, 91)), false);
ok("90%: both over 90, other 6 lower -> move to the lower", autoShouldMove(A(1, 97), A(2, 91)), "90");
ok("90%: moved chat does not bounce back (other is higher)", autoShouldMove(A(2, 91), A(1, 97)), false);
ok("90%: other one is higher -> stay", autoShouldMove(A(1, 90), A(2, 93)), false);
ok("90%: other logged out -> stay", autoShouldMove(A(1, 95), A(2, 0, 0, { key: false })), false);
ok("idle move: 15+ points higher -> move", autoShouldMove(A(1, 40), A(2, 25)), "gap");
ok("idle move: 14 points -> stay (no flapping)", autoShouldMove(A(1, 39), A(2, 25)), false);
ok("idle move: current spent -> move", autoShouldMove(A(1, 98), A(2, 90)), "spent");
ok("idle move: current weekly spent -> move", autoShouldMove(A(1, 10, 99), A(2, 20)), "spent");
ok("idle move: current logged out here -> move", autoShouldMove(A(1, 10, 10, { key: false }), A(2, 20)), "spent");
ok("idle move: current held -> move", autoShouldMove(A(1, 10, 10, { held: true }), A(2, 20)), "spent");
ok("both spent -> stay put (the governor takes over)", autoShouldMove(A(1, 99), A(2, 98)), false);
ok("new chats: both over 90 -> the lower one", pickAccount([A(1, 95), A(2, 91)]), 2);
ok("idle move: no reading for current -> stay", autoShouldMove(A(1, null), A(2, 0)), false);
ok("idle move: same account -> stay", autoShouldMove(A(2, 50), A(2, 50)), false);
console.log(`\n${n} passed`);
